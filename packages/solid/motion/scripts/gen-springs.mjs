// Regenerates src/springs.css from the spring compiler. Run from the package
// directory after building (`pnpm build`), since it imports the bundle:
//   node scripts/gen-springs.mjs
import { writeFileSync } from "node:fs";
import { createSpring, springPresets } from "../dist/index.mjs";

// Starting-point durations per preset. Shape comes from the spring; length is
// a design choice — tune freely.
const DURATIONS = {
  gentle: "450ms",
  default: "320ms",
  snappy: "220ms",
  bouncy: "550ms",
};

const lines = [
  "/* Spring easing tokens. Reference these in transitions; declare a plain",
  " * `ease` fallback first for engines without `linear()` (Chrome < 113,",
  " * Firefox < 112, Safari < 17.2). Generated by `pnpm gen:springs` — do not",
  " * hand-edit. */",
  ":root {",
];
for (const [name, params] of Object.entries(springPresets)) {
  lines.push(`  --solidix-spring-${name}: ${createSpring(params)};`);
  lines.push(`  --solidix-spring-${name}-duration: ${DURATIONS[name]};`);
}
lines.push("}", "");
writeFileSync(new URL("../src/springs.css", import.meta.url), lines.join("\n"));
console.log("wrote src/springs.css");
