function renderDeclaration(name: string, value: string): string {
  const single = `  ${name}: ${value};`;
  return single.length <= 100 ? single : `  ${name}:\n    ${value};`;
}

function renderRootBlock(light: TokenSet, dark: TokenSet): string {
  const lines = [":root {"];
  for (const [name, value] of Object.entries(light)) {
    const darkValue = dark[name];
    if (darkValue === undefined) {
      lines.push(renderDeclaration(name, value));
    } else {
      lines.push(renderDeclaration(name, value));
      lines.push(renderDeclaration(name, `light-dark(${value}, ${darkValue})`));
    }
  }
  lines.push("}", "");
  return lines.join("\n");
}

/** Renders the full `tokens.css` output from the token source of truth. */
export function renderTokensCss(): string {
  return HEADER + renderRootBlock(lightTokens, darkTokens) + backendBaseCss;
}

function channelToLinear(value: number): number {
  const s = value / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

function parseHex(hex: string): [number, number, number] {
  const normalized = hex.startsWith("#") ? hex.slice(1) : hex;
  const full =
    normalized.length === 3
      ? normalized
          .split("")
          .map((part) => part + part)
          .join("")
      : normalized;
  const int = Number.parseInt(full, 16);
  return [(int >> 16) & 255, (int >> 8) & 255, int & 255];
}

/** Relative-luminance contrast ratio between two hex colors. */
export function contrastRatio(foreground: string, background: string): number {
  const luminance = (hex: string) => {
    const [r, g, b] = parseHex(hex).map(channelToLinear);
    return 0.2126 * r! + 0.7152 * g! + 0.0722 * b!;
  };
  const lighter = Math.max(luminance(foreground), luminance(background));
  const darker = Math.min(luminance(foreground), luminance(background));
  return (lighter + 0.05) / (darker + 0.05);
}

/** One foreground/background pair checked for contrast. */
export type ContrastPair = {
  /** Human-readable pair name used in test output. */
  name: string;
  /** Foreground hex color. */
  foreground: string;
  /** Background hex color. */
  background: string;
  /** Minimum ratio the pair must meet. */
  min: number;
};

